export function formatUsd(value: number, opts?: { compact?: boolean }): string {
  if (opts?.compact) {
    return new Intl.NumberFormat("en-US", {
      style: "currency",
      currency: "USD",
      notation: "compact",
      maximumFractionDigits: 2,
    }).format(value);
  }
  // Negative amounts need the same precision rule, judged on magnitude.
  const magnitude = Math.abs(value);
  // Whole-dollar amounts and exact zeros read best with two decimals; sub-cent
  // totals keep more precision.
  const digits = magnitude >= 1 || magnitude === 0 ? 2 : magnitude >= 0.01 ? 4 : 6;
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(value);
}

export function formatPct(value: number): string {
  const sign = value >= 0 ? "+" : "";
  return `${sign}${value.toFixed(2)}%`;
}
